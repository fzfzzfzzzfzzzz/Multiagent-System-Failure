"""Scoped SSH helper. Credentials are read in memory, never persisted or printed.

Examples: python scripts/remote.py inspect --host 151 --credentials-pdf fangc-README.pdf
The optional --command is an explicit operator command, not generated by an agent.
"""
import argparse
import contextlib
import json
import logging
import os
